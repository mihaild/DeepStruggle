"""Construction of specific game positions for behavioural testing.

A behavioural test needs a position the engine agrees is legal: the right cards in the
right hand, the board and DEFCON set, and the decision context pointing at the player
whose choice we want to inspect. Everything here goes through the engine's own setters, so
the resulting action mask is generated by the same code training uses -- a position that
the engine would not produce is a position whose test result means nothing.

Two decision nodes matter:

* ``SELECT_CARD`` -- which card to play. Flat actions 0..109 are card ids 1..110.
* ``SELECT_PLAY_MODE`` -- how to play it. Flat actions 110..113 are EVENT, OPS, SPACE, PASS.

So "should the US play NATO for the event?" is a question about the *second* node, reached
by stepping the first.
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import ts_engine as ts

from bindings.action_encoder import ActionEncoder

CARD_ACTION_START = 0
PLAY_MODE_START = 110

#: P17: a card play is ONE decision now. `ops` no longer exists on its own -- the Ops mode is
#: chosen at the same node -- so it is an alias for placement, which is the mode that is always
#: offered when Ops play is legal at all. Callers that care which mode should name it.
#:
#: `pass` is gone: PlayMode::PASS was never set by any mask, so it addressed a permanently dead
#: slot.
PLAY_MODE_ACTION: Dict[str, int] = {
    "event": PLAY_MODE_START + int(ts.Resolution.EVENT),
    "space": PLAY_MODE_START + int(ts.Resolution.SPACE),
    "ops": PLAY_MODE_START + int(ts.Resolution.OPS_INFLUENCE),
    "ops_influence": PLAY_MODE_START + int(ts.Resolution.OPS_INFLUENCE),
    "ops_coup": PLAY_MODE_START + int(ts.Resolution.OPS_COUP),
    "ops_realign": PLAY_MODE_START + int(ts.Resolution.OPS_REALIGN),
}


def card_action(card_id: int) -> int:
    """Flat action index that selects `card_id` at a SELECT_CARD node."""
    if not 1 <= card_id <= 110:
        raise ValueError(f"card id out of range: {card_id}")
    return CARD_ACTION_START + card_id - 1


@dataclass
class PositionBuilder:
    """Declarative description of a position, materialised by :meth:`build`."""

    hand: Sequence[int]
    side: ts.Player
    opponent_hand: Sequence[int] = field(default_factory=tuple)
    flags: Sequence[int] = field(default_factory=tuple)
    discard: Sequence[int] = field(default_factory=tuple)
    influence: Sequence[Tuple[int, ts.Player, int]] = field(default_factory=tuple)
    clear_influence: Sequence[Tuple[int, ts.Player]] = field(default_factory=tuple)
    defcon: int = 3
    turn: int = 3
    action_round: int = 1
    victory_points: int = 0
    us_space: Optional[int] = None
    ussr_space: Optional[int] = None
    seed: int = 20260830

    def build(self) -> ts.GameState:
        st = ts.GameState()
        ts.Engine.init_game(st, self.seed)

        # Start from an empty deal so only the cards named below are held.
        for cid in range(1, 111):
            if st.get_card_location(cid) in (ts.hand_of(ts.Player.US), ts.hand_of(ts.Player.USSR)):
                st.set_card_location(cid, ts.CardLocation.DRAW_DECK)

        mine = ts.hand_of(ts.Player.US) if self.side == ts.Player.US else ts.hand_of(ts.Player.USSR)
        theirs = ts.hand_of(ts.Player.USSR) if self.side == ts.Player.US else ts.hand_of(ts.Player.US)
        for cid in self.hand:
            st.set_card_location(cid, mine)
        for cid in self.opponent_hand:
            st.set_card_location(cid, theirs)
        for cid in self.discard:
            st.set_card_location(cid, ts.CardLocation.DISCARD_PILE)

        for flag in self.flags:
            st.set_flag(flag)

        # set_country takes explicit (us, ussr) amounts, so read the current pair and
        # rewrite only the side being changed.
        def _set(country_id: int, player: ts.Player, amount: int) -> None:
            cur = st.get_country(country_id)
            us = amount if player == ts.Player.US else int(cur.us_influence)
            ussr = amount if player == ts.Player.USSR else int(cur.ussr_influence)
            st.set_country(country_id, us, ussr)

        for country_id, player, amount in self.influence:
            _set(country_id, player, amount)
        for country_id, player in self.clear_influence:
            _set(country_id, player, 0)

        st.defcon = self.defcon
        st.turn = self.turn
        st.action_round = self.action_round
        st.victory_points = self.victory_points
        if self.us_space is not None:
            st.us_space_track = self.us_space
        if self.ussr_space is not None:
            st.ussr_space_track = self.ussr_space

        st.current_phase = ts.Phase.ACTION_ROUND
        st.phasing_player = self.side
        ctx = st.ctx()
        ctx.decision_player = self.side
        ctx.decision_type = ts.DecisionType.SELECT_CARD
        return st


def build_action_round_position(builder: PositionBuilder) -> ts.GameState:
    return builder.build()


def legal_mask(state: ts.GameState) -> np.ndarray:
    return ActionEncoder.get_legal_mask(state)


def step_to_play_mode(state: ts.GameState, card_id: int) -> ts.GameState:
    """Selects `card_id`, leaving the state at its SELECT_PLAY_MODE node.

    Raises if the card is not selectable or the engine does not land on a play-mode
    decision, so a malformed position fails loudly instead of silently testing the wrong
    question.
    """
    mask = legal_mask(state)
    action = card_action(card_id)
    if mask[action] != 1:
        legal = [int(i) + 1 for i in np.flatnonzero(mask) if i < 110]
        raise ValueError(f"card {card_id} is not selectable here; selectable cards: {legal}")
    nxt = state.clone()
    ts.Engine.step_flat(nxt, action)
    if nxt.ctx().decision_type != ts.DecisionType.SELECT_PLAY_MODE:
        raise ValueError(
            f"after selecting card {card_id} the engine is at {nxt.ctx().decision_type}, "
            "not SELECT_PLAY_MODE"
        )
    return nxt


def legal_play_modes(state: ts.GameState) -> List[str]:
    mask = legal_mask(state)
    return [name for name, idx in PLAY_MODE_ACTION.items() if mask[idx] == 1]
